#!/usr/bin/env python3
"""Per-project progress records (.claude/dashboard/) and Claude Code hook entrypoints.

Data lives in <project>/.claude/dashboard/{status,decisions}.json. A project opts in
by running `progress.py init`; hooks exit silently everywhere else.
Standard library only, so hooks never depend on a venv.
"""

import argparse
import contextlib
import hashlib
import datetime as dt
import errno
import fcntl
import json
import os
import re
import subprocess
import sys
import tempfile
import time
import traceback
from pathlib import Path

SCHEMA = 1
DATA_DIR = Path(".claude") / "dashboard"
TASK_STATUSES = ("todo", "doing", "unverified", "done", "blocked", "dropped")
TEST_RESULTS = ("pass", "fail", "skip")
MAX_EVENTS = 200
MAX_SESSIONS = 30
MAX_SESSION_COMMITS = 20
LOCK_WAIT_SEC = 3.0
GIT_TIMEOUT_SEC = 2.0
# Stop fires on every turn; only touch the file when this much time has passed.
HEARTBEAT_SEC = 300
# Parallel sessions in one project are normal (herdr); only close ones silent this long.
STALE_SESSION_SEC = 1800
SESSION_ID_RE = re.compile(r"^[A-Za-z0-9_-]{1,128}$")

GITIGNORE = """\
# Generated by progress-dashboard. status.json / decisions.json are tracked.
dashboard.html
hook.log
.lock
*.tmp
"""

_SECRET_PATTERNS = [
    (re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----.*?(-----END [A-Z ]*PRIVATE KEY-----|$)", re.S),
     "[REDACTED PRIVATE KEY]"),
    (re.compile(r"\b(gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,})"), "[REDACTED]"),
    (re.compile(r"\bsk-[A-Za-z0-9_-]{20,}"), "[REDACTED]"),
    (re.compile(r"\bAKIA[0-9A-Z]{16}\b"), "[REDACTED]"),
    (re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}"), "[REDACTED]"),
    (re.compile(r"(?i)\bbearer\s+[A-Za-z0-9._~+/=-]{16,}"), "Bearer [REDACTED]"),
    (re.compile(r"(?i)\b([a-z][a-z0-9+.-]*://)[^/\s:@]+:[^/\s@]+@"), r"\1[REDACTED]@"),
    (re.compile(r"(?i)\b(password|passwd|pwd|secret|token|api[_-]?key|access[_-]?key)(\s*[:=]\s*)(\"[^\"]*\"|'[^']*'|\S+)"),
     r"\1\2[REDACTED]"),
]


def redact(text):
    if not isinstance(text, str):
        return text
    for pattern, repl in _SECRET_PATTERNS:
        text = pattern.sub(repl, text)
    return text


def now_iso():
    return dt.datetime.now().astimezone().isoformat(timespec="seconds")


def parse_iso(value):
    try:
        return dt.datetime.fromisoformat(value)
    except (TypeError, ValueError):
        return None


class ProgressError(Exception):
    pass


# ---------------------------------------------------------------- storage

def find_root(start):
    p = Path(start).resolve()
    for d in (p, *p.parents):
        if (d / DATA_DIR / "status.json").is_file():
            return d
    return None


def data_dir(root):
    return Path(root) / DATA_DIR


def locked(root, wait=LOCK_WAIT_SEC):
    """Serialize read-modify-write across concurrent sessions and hooks."""
    return locked_file(data_dir(root) / ".lock", wait)


@contextlib.contextmanager
def locked_file(path, wait=LOCK_WAIT_SEC):
    fd = os.open(path, os.O_RDWR | os.O_CREAT, 0o644)
    deadline = time.monotonic() + wait
    try:
        while True:
            try:
                fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                break
            except OSError as e:
                if e.errno not in (errno.EAGAIN, errno.EACCES):
                    raise
                if time.monotonic() >= deadline:
                    raise ProgressError("lock busy: another progress update is running")
                time.sleep(0.05)
        yield
    finally:
        os.close(fd)


def atomic_write_text(path, text):
    path = Path(path)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(FileNotFoundError):
            os.unlink(tmp)
        raise
    dfd = os.open(path.parent, os.O_RDONLY)
    try:
        os.fsync(dfd)
    finally:
        os.close(dfd)


def load_json(path, default):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except FileNotFoundError:
        return default
    except json.JSONDecodeError as e:
        # Never overwrite a file we failed to parse; the user must fix it first.
        raise ProgressError(f"{path} is not valid JSON ({e}); refusing to overwrite") from e


def save_json(path, obj):
    atomic_write_text(path, json.dumps(obj, ensure_ascii=False, indent=2) + "\n")


def empty_status(name):
    return {
        "schema": SCHEMA,
        "project": name,
        "updated_at": now_iso(),
        "goal": "",
        "tasks": [],
        "blockers": [],
        "tests": [],
        "next_actions": [],
        "sessions": [],
        "events": [],
        "git": {},
    }


def load_status(root):
    st = load_json(data_dir(root) / "status.json", None)
    if st is None:
        raise ProgressError(f"no status.json under {data_dir(root)}; run `progress.py init`")
    base = empty_status(st.get("project") or Path(root).name)
    base.update(st)
    return base


def load_decisions(root):
    d = load_json(data_dir(root) / "decisions.json", {"schema": SCHEMA, "decisions": []})
    d.setdefault("decisions", [])
    return d


def save_status(root, st, touch=True):
    if touch:
        st["updated_at"] = now_iso()
    st["events"] = st["events"][-MAX_EVENTS:]
    st["sessions"] = st["sessions"][-MAX_SESSIONS:]
    save_json(data_dir(root) / "status.json", st)


def next_id(items, prefix):
    n = 0
    for it in items:
        m = re.fullmatch(prefix + r"(\d+)", str(it.get("id", "")))
        if m:
            n = max(n, int(m.group(1)))
    return f"{prefix}{n + 1}"


def find_item(items, item_id, kind):
    for it in items:
        if it.get("id") == item_id:
            return it
    raise ProgressError(f"{kind} {item_id} not found")


def current_session_id():
    sid = os.environ.get("PROGRESS_SESSION_ID", "")
    return sid if SESSION_ID_RE.match(sid) else "manual"


def add_event(st, kind, text, session=None):
    st["events"].append({
        "at": now_iso(),
        "session": session or current_session_id(),
        "kind": kind,
        "text": redact(text),
    })


# ---------------------------------------------------------------- git

def git(root, *args):
    try:
        r = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True,
                           timeout=GIT_TIMEOUT_SEC)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return r.stdout.strip() if r.returncode == 0 else None


def git_head(root):
    return git(root, "rev-parse", "HEAD")


def git_snapshot(root):
    head = git_head(root)
    if head is None:
        return {"available": False, "checked_at": now_iso()}
    porcelain = git(root, "status", "--porcelain=v1", "--untracked-files=normal") or ""
    lines = [ln for ln in porcelain.splitlines() if ln.strip()]
    return {
        "available": True,
        "branch": git(root, "rev-parse", "--abbrev-ref", "HEAD") or "",
        "head": head,
        "head_subject": redact(git(root, "log", "-1", "--format=%s") or ""),
        "dirty_files": len(lines),
        "untracked_files": sum(1 for ln in lines if ln.startswith("??")),
        "checked_at": now_iso(),
    }


def commits_between(root, start, end):
    if not start or not end or start == end:
        return []
    out = git(root, "log", "--format=%h %s", f"-{MAX_SESSION_COMMITS}", f"{start}..{end}")
    return [redact(ln) for ln in (out or "").splitlines()]


# ---------------------------------------------------------------- rendering glue

def _sibling(name):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    # Keep the dotfiles checkout free of __pycache__ next to the scripts.
    sys.dont_write_bytecode = True
    return __import__(name)


def view(root, st, dec):
    """What to display: the project's own source of truth replaces tasks/decisions if set."""
    src = st.get("sources") or {}
    if not src:
        return st, dec
    sources = _sibling("sources")
    st = dict(st)
    if src.get("tasks"):
        st["tasks"] = sources.read_backlog(Path(root) / src["tasks"])
    if src.get("decisions"):
        dec = {"decisions": sources.read_decisions(Path(root) / src["decisions"], Path(root))}
    return st, dec


def owned_elsewhere(st, kind):
    src = (st.get("sources") or {}).get(kind)
    if src:
        raise ProgressError(f"this project's {kind} live in {src} (the source of truth); edit that file instead")


def render(root, st=None, dec=None):
    renderer = _sibling("render")
    st = st if st is not None else load_status(root)
    dec = dec if dec is not None else load_decisions(root)
    st, dec = view(root, st, dec)
    html_text = renderer.render_html(st, dec, current_head=(st.get("git") or {}).get("head"))
    atomic_write_text(data_dir(root) / "dashboard.html", html_text)


def html_is_stale(root):
    d = data_dir(root)
    try:
        html_m = (d / "dashboard.html").stat().st_mtime
    except FileNotFoundError:
        return True
    for name in ("status.json", "decisions.json"):
        with contextlib.suppress(FileNotFoundError):
            if (d / name).stat().st_mtime > html_m:
                return True
    with contextlib.suppress(FileNotFoundError, json.JSONDecodeError):
        src = (json.loads((d / "status.json").read_text(encoding="utf-8")).get("sources") or {})
        if src and _sibling("sources").source_mtime(root, src) > html_m:
            return True
    return False


# ---------------------------------------------------------------- registry
# serve.py shows every registered project on one page, so one hub covers all repos.

def registry_path():
    override = os.environ.get("PROGRESS_REGISTRY")
    if override:
        return Path(override)
    state = os.environ.get("XDG_STATE_HOME") or str(Path.home() / ".local" / "state")
    return Path(state) / "progress-dashboard" / "projects.json"


def project_slug(root):
    root = str(Path(root).resolve())
    name = re.sub(r"[^A-Za-z0-9._-]", "-", Path(root).name) or "project"
    # Worktrees of one repo share a basename; the path hash keeps their slugs apart.
    return f"{name}-{hashlib.sha1(root.encode()).hexdigest()[:6]}"


def load_registry():
    data = load_json(registry_path(), {"projects": []})
    data.setdefault("projects", [])
    return data


def register_project(root):
    """Best effort: a registry problem must never break a hook or a CLI update."""
    root = str(Path(root).resolve())
    path = registry_path()
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        with locked_file(path.with_suffix(".lock")):
            reg = load_registry()
            if any(p.get("root") == root for p in reg["projects"]):
                return
            reg["projects"].append({"root": root, "slug": project_slug(root), "added_at": now_iso()})
            save_json(path, reg)
    except Exception as e:  # noqa: BLE001
        log_hook(root, f"register failed: {e!r}")


def unregister_project(root):
    root = str(Path(root).resolve())
    path = registry_path()
    with locked_file(path.with_suffix(".lock")):
        reg = load_registry()
        before = len(reg["projects"])
        reg["projects"] = [p for p in reg["projects"] if p.get("root") != root]
        save_json(path, reg)
    return before != len(reg["projects"])


# ---------------------------------------------------------------- summary

STATUS_JA = {"todo": "未着手", "doing": "進行中", "unverified": "未検証", "done": "完了",
             "blocked": "ブロック中", "dropped": "中止",
             # Only produced when tasks come from a project's own backlog (sources.py).
             "open": "未完", "waiting": "外部待ち", "closed": "閉じた"}


def brief(root, st, dec, limit=3):
    """Short text injected at SessionStart. Keep it under ~15 lines."""
    st, dec = view(root, st, dec)
    tasks = st["tasks"]
    count = {s: sum(1 for t in tasks if t.get("status") == s) for s in STATUS_JA}
    lines = [f"[progress-dashboard] {st['project']} (最終更新 {st.get('updated_at', '-')})"]
    if st.get("goal"):
        lines.append(f"目標: {st['goal']}")
    lines.append("タスク: " + " / ".join(f"{STATUS_JA[s]}{count[s]}" for s in STATUS_JA
                                           if s not in ("dropped", "closed") and count[s]) if tasks else "タスク: なし")
    for t in [t for t in tasks if t.get("status") == "waiting"][:limit]:
        lines.append(f"外部待ち {t['id']}: {t['title']}")
    open_blockers = [b for b in st["blockers"] if not b.get("resolved_at")]
    for b in open_blockers[:limit]:
        lines.append(f"ブロッカー {b['id']}: {b['text']}")
    for t in [t for t in tasks if t.get("status") in ("doing", "unverified")][:limit]:
        lines.append(f"{STATUS_JA[t['status']]} {t['id']}: {t['title']}")
    nxt = [n for n in st["next_actions"] if not n.get("done_at")]
    for n in nxt[:limit]:
        lines.append(f"次 {n['id']}: {n['text']}")
    # A backlog read from Markdown has no per-row dates, so "latest done" would be a guess.
    done = [t for t in tasks if t.get("status") == "done" and t.get("updated_at")]
    if done:
        last = max(done, key=lambda t: t["updated_at"])
        lines.append(f"直近の完了 {last['id']}: {last['title']}")
    active = sorted((d for d in dec["decisions"] if d.get("status", "active") == "active"),
                    key=lambda d: d.get("at", ""), reverse=True)
    if active:
        lines.append("最近の判断: " + " / ".join(f"{d['id']} {d['title']}" for d in active[:limit]))
    failing = [t for t in st["tests"] if t.get("result") == "fail"]
    if failing:
        lines.append("失敗中のテスト: " + ", ".join(t["name"] for t in failing[:limit]))
    src = st.get("sources") or {}
    if src.get("tasks"):
        lines.append(f"残件と判断の正本は {src['tasks']} と {src.get('decisions', 'notes')}/ (ダッシュボードは読むだけ)。"
                     "テスト結果・方針変更・セッション要約だけ progress-dashboard skill で記録する。")
    else:
        lines.append("タスク完了・設計判断・テスト結果・ブロッカー・方針変更があれば progress-dashboard skill で記録する。")
    lines.append(f"詳細: {data_dir(root) / 'dashboard.html'}")
    return "\n".join(redact(ln) for ln in lines)


# ---------------------------------------------------------------- hooks

def log_hook(root, msg):
    with contextlib.suppress(Exception):
        path = data_dir(root) / "hook.log"
        if path.exists() and path.stat().st_size > 256 * 1024:
            os.replace(path, path.with_suffix(".log.1"))
        with open(path, "a", encoding="utf-8") as f:
            f.write(f"{now_iso()} {msg}\n")


def session_entry(st, sid):
    for s in st["sessions"]:
        if s.get("id") == sid:
            return s
    return None


def sweep_orphan_tmp(root, max_age_sec=60):
    cutoff = time.time() - max_age_sec
    for tmp in data_dir(root).glob("*.tmp"):
        with contextlib.suppress(FileNotFoundError):
            if tmp.stat().st_mtime < cutoff:
                tmp.unlink()


def hook_session_start(root, payload):
    sid = payload.get("session_id") or ""
    if not SESSION_ID_RE.match(sid):
        sid = "unknown"
    source = str(payload.get("source") or "startup")
    with locked(root):
        sweep_orphan_tmp(root)
        st = load_status(root)
        dec = load_decisions(root)
        snap = git_snapshot(root)
        st["git"] = snap
        now = dt.datetime.now().astimezone()
        for s in st["sessions"]:
            seen = parse_iso(s.get("last_seen_at") or s.get("started_at"))
            stale = seen is None or (now - seen).total_seconds() >= STALE_SESSION_SEC
            if s.get("id") != sid and not s.get("ended_at") and stale:
                # SessionEnd never arrived (crash, kill, power loss). If that session is
                # in fact still alive, its next Stop hook reopens the entry.
                s["ended_at"] = s.get("last_seen_at") or s.get("started_at")
                s["end_reason"] = "missing"
                add_event(st, "recover", f"セッション {s.get('id', '?')[:8]} の終了記録が無いため、最終応答時刻で閉じた", sid)
        s = session_entry(st, sid)
        if s is None:
            st["sessions"].append({
                "id": sid, "started_at": now_iso(), "source": source,
                "last_seen_at": now_iso(), "ended_at": None, "end_reason": None,
                "branch": snap.get("branch"), "head_start": snap.get("head"),
                "head_end": None, "commits": [], "summary": "",
            })
        else:
            s["ended_at"] = None
            s["end_reason"] = None
            s["last_seen_at"] = now_iso()
        save_status(root, st, touch=False)
        render(root, st, dec)
    register_project(root)
    env_file = os.environ.get("CLAUDE_ENV_FILE")
    if env_file and sid != "unknown":
        with open(env_file, "a", encoding="utf-8") as f:
            f.write(f"export PROGRESS_SESSION_ID={sid}\n")
    print(brief(root, st, dec))


def hook_stop(root, payload):
    if payload.get("stop_hook_active"):
        return
    sid = payload.get("session_id") or ""
    head = git_head(root)
    st = load_status(root)
    s = session_entry(st, sid)
    last = parse_iso((s or {}).get("last_seen_at"))
    heartbeat_due = s is None or last is None or \
        (dt.datetime.now().astimezone() - last).total_seconds() >= HEARTBEAT_SEC
    head_moved = head is not None and head != (st.get("git") or {}).get("head")
    reopened = s is not None and s.get("end_reason") == "missing"
    if not (heartbeat_due or head_moved or reopened or html_is_stale(root)):
        return
    with locked(root, wait=1.0):
        st = load_status(root)
        s = session_entry(st, sid)
        changed = False
        if s is not None and (heartbeat_due or reopened):
            s["last_seen_at"] = now_iso()
            if reopened:
                s["ended_at"] = None
                s["end_reason"] = None
            changed = True
        if head_moved:
            st["git"] = git_snapshot(root)
            if s is not None:
                s["commits"] = commits_between(root, s.get("head_start"), head)
            changed = True
        if changed:
            save_status(root, st, touch=False)
        if changed or html_is_stale(root):
            render(root, st)


def hook_session_end(root, payload):
    sid = payload.get("session_id") or ""
    reason = str(payload.get("reason") or "other")
    with locked(root):
        st = load_status(root)
        snap = git_snapshot(root)
        st["git"] = snap
        s = session_entry(st, sid)
        if s is not None:
            s["ended_at"] = now_iso()
            s["last_seen_at"] = s["ended_at"]
            s["end_reason"] = reason
            s["head_end"] = snap.get("head")
            s["commits"] = commits_between(root, s.get("head_start"), snap.get("head"))
        save_status(root, st, touch=True)
        render(root, st)


HOOKS = {"session-start": hook_session_start, "stop": hook_stop, "session-end": hook_session_end}


def run_hook(name):
    """Hooks must never block or break the session: always exit 0."""
    root = None
    try:
        raw = sys.stdin.read() if not sys.stdin.isatty() else ""
        payload = json.loads(raw) if raw.strip() else {}
        if payload.get("agent_id"):
            return 0
        # Waiting-for-user state is per session and project-independent, so record it first.
        with contextlib.suppress(Exception):
            _sibling("agents").record(payload)
        if name == "agent":
            return 0
        start = payload.get("cwd") or os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()
        root = find_root(start)
        if root is None and os.environ.get("CLAUDE_PROJECT_DIR"):
            root = find_root(os.environ["CLAUDE_PROJECT_DIR"])
        if root is None:
            return 0
        HOOKS[name](root, payload)
    except Exception as e:  # noqa: BLE001
        if root is not None:
            log_hook(root, f"{name} failed: {e!r}\n{traceback.format_exc()}")
    return 0


# ---------------------------------------------------------------- CLI commands

def cmd_init(root, args):
    d = data_dir(root)
    d.mkdir(parents=True, exist_ok=True)
    gi = d / ".gitignore"
    if not gi.exists():
        atomic_write_text(gi, GITIGNORE)
    with locked(root):
        if (d / "status.json").exists():
            st = load_status(root)
            print(f"already initialized: {d}")
        else:
            st = empty_status(args.name or Path(root).name)
            st["goal"] = redact(args.goal or "")
            src = {}
            for kind, rel in (("tasks", args.tasks_from), ("decisions", args.decisions_from)):
                if rel:
                    if not (Path(root) / rel).exists():
                        raise ProgressError(f"{rel} not found under {root}")
                    src[kind] = rel
            if src:
                st["sources"] = src
            st["git"] = git_snapshot(root)
            add_event(st, "init", "ダッシュボードを初期化")
            save_status(root, st)
            if not (d / "decisions.json").exists():
                save_json(d / "decisions.json", {"schema": SCHEMA, "decisions": []})
            print(f"initialized: {d}")
        render(root, st)
    register_project(root)


def mutate(root, fn):
    with locked(root):
        st = load_status(root)
        dec = load_decisions(root)
        msg = fn(st, dec)
        save_status(root, st)
        save_json(data_dir(root) / "decisions.json", dec)
        try:
            render(root, st, dec)
        except Exception as e:  # noqa: BLE001
            # Data is already saved; a broken renderer must not lose the record.
            log_hook(root, f"render failed after CLI update: {e!r}")
            msg = f"{msg} (dashboard render failed, see hook.log)"
    if msg:
        print(msg)


def cmd_goal(root, args):
    def fn(st, dec):
        st["goal"] = redact(args.text)
        add_event(st, "goal", f"目標を更新: {args.text}")
        return "goal updated"
    mutate(root, fn)


def open_blocker(st, task_id, text):
    bid = next_id(st["blockers"], "B")
    st["blockers"].append({"id": bid, "text": redact(text), "task": task_id,
                           "created_at": now_iso(), "resolved_at": None, "resolution": ""})
    return bid


def cmd_task(root, args):
    def fn(st, dec):
        owned_elsewhere(st, "tasks")
        if args.action == "add":
            tid = next_id(st["tasks"], "T")
            status = args.status or "todo"
            if status == "done":
                raise ProgressError("add the task first, then `task set ID done --evidence ...`")
            if status == "blocked" and not (args.note or "").strip():
                raise ProgressError("blocked requires --note describing the blocker")
            st["tasks"].append({
                "id": tid, "title": redact(args.title), "status": status,
                "note": redact(args.note or ""), "evidence": "",
                "created_at": now_iso(), "updated_at": now_iso(),
                "session": current_session_id(),
            })
            add_event(st, "task", f"{tid} を追加 ({STATUS_JA[status]}): {args.title}")
            if status == "blocked":
                open_blocker(st, tid, args.note)
            return tid
        t = find_item(st["tasks"], args.id, "task")
        status = args.status
        if status == "done" and not (args.evidence or "").strip():
            raise ProgressError("done requires --evidence (test name, command, or check that "
                                "verified it). Use `unverified` if it is implemented but not verified.")
        if status == "blocked" and not (args.note or "").strip():
            raise ProgressError("blocked requires --note describing the blocker")
        if t.get("status") == "blocked" and status != "blocked":
            # The task moving on is what resolves its blocker; leaving it open would lie.
            for b in st["blockers"]:
                if b.get("task") == t["id"] and not b.get("resolved_at"):
                    b["resolved_at"] = now_iso()
                    b["resolution"] = redact(args.evidence or args.note or f"{t['id']} が{STATUS_JA[status]}になった")
        t["status"] = status
        if args.note:
            t["note"] = redact(args.note)
        if args.evidence:
            t["evidence"] = redact(args.evidence)
        if args.title:
            t["title"] = redact(args.title)
        t["updated_at"] = now_iso()
        t["session"] = current_session_id()
        detail = f" ({args.evidence or args.note})" if (args.evidence or args.note) else ""
        add_event(st, "task", f"{t['id']} → {STATUS_JA[status]}: {t['title']}{detail}")
        if status == "blocked":
            open_blocker(st, t["id"], args.note)
        return f"{t['id']} -> {status}"
    mutate(root, fn)


def cmd_blocker(root, args):
    def fn(st, dec):
        owned_elsewhere(st, "tasks")
        if args.action == "add":
            bid = next_id(st["blockers"], "B")
            st["blockers"].append({"id": bid, "text": redact(args.text), "task": args.task or "",
                                   "created_at": now_iso(), "resolved_at": None, "resolution": ""})
            add_event(st, "blocker", f"{bid} を発見: {args.text}")
            return bid
        b = find_item(st["blockers"], args.id, "blocker")
        b["resolved_at"] = now_iso()
        b["resolution"] = redact(args.resolution)
        add_event(st, "blocker", f"{b['id']} を解消: {args.resolution}")
        return f"{b['id']} resolved"
    mutate(root, fn)


def cmd_test(root, args):
    def fn(st, dec):
        head = git_head(root)
        snap_dirty = None
        porcelain = git(root, "status", "--porcelain=v1", "--untracked-files=no")
        if porcelain is not None:
            snap_dirty = bool(porcelain.strip())
        rec = {"name": redact(args.name), "result": args.result, "command": redact(args.cmd or ""),
               "detail": redact(args.detail or ""), "at": now_iso(), "git_head": head,
               "git_dirty": snap_dirty, "session": current_session_id()}
        st["tests"] = [t for t in st["tests"] if t.get("name") != rec["name"]] + [rec]
        label = {"pass": "成功", "fail": "失敗", "skip": "未実施"}[args.result]
        add_event(st, "test", f"{args.name}: {label}" + (f" ({args.detail})" if args.detail else ""))
        return f"test {args.name}: {args.result}"
    mutate(root, fn)


def cmd_decision(root, args):
    def fn(st, dec):
        owned_elsewhere(st, "decisions")
        items = dec["decisions"]
        if args.action == "add":
            did = next_id(items, "D")
            items.append({
                "id": did, "at": now_iso(), "title": redact(args.title),
                "decision": redact(args.decision), "reason": redact(args.reason),
                "alternatives": [redact(a) for a in args.alt or []],
                "assumptions": [redact(a) for a in args.assume or []],
                "refs": [redact(r) for r in args.ref or []],
                "status": "active", "superseded_by": None, "session": current_session_id(),
            })
            add_event(st, "decision", f"{did}: {args.title}")
            return did
        d = find_item(items, args.id, "decision")
        find_item(items, args.by, "decision")
        d["status"] = "superseded"
        d["superseded_by"] = args.by
        add_event(st, "decision", f"{d['id']} は {args.by} で置き換え")
        return f"{d['id']} superseded by {args.by}"
    mutate(root, fn)


def cmd_next(root, args):
    def fn(st, dec):
        owned_elsewhere(st, "tasks")
        if args.action == "add":
            nid = next_id(st["next_actions"], "N")
            st["next_actions"].append({"id": nid, "text": redact(args.text),
                                       "created_at": now_iso(), "done_at": None})
            return nid
        n = find_item(st["next_actions"], args.id, "next action")
        n["done_at"] = now_iso()
        return f"{n['id']} done"
    mutate(root, fn)


def cmd_note(root, args):
    def fn(st, dec):
        kind = "pivot" if args.pivot else "note"
        add_event(st, kind, args.text)
        return kind
    mutate(root, fn)


def cmd_summary(root, args):
    def fn(st, dec):
        sid = current_session_id()
        s = session_entry(st, sid)
        if s is None:
            # Outside a hooked session nothing will ever close this row, so close it now.
            manual = sid == "manual"
            s = {"id": sid, "started_at": now_iso(), "source": "manual", "last_seen_at": now_iso(),
                 "ended_at": now_iso() if manual else None, "end_reason": "manual" if manual else None,
                 "branch": None, "head_start": git_head(root), "head_end": None, "commits": [],
                 "summary": ""}
            st["sessions"].append(s)
        s["summary"] = redact(args.text)
        return f"session {sid[:8]} summary set"
    mutate(root, fn)


def cmd_show(root, args):
    print(brief(root, load_status(root), load_decisions(root)))


def cmd_unregister(root, args):
    removed = unregister_project(root)
    print(f"{'unregistered' if removed else 'not registered'}: {root} "
          "(the next init, render or SessionStart here registers it again)")


def cmd_render(root, args):
    with locked(root):
        st = load_status(root)
        st["git"] = git_snapshot(root)
        save_status(root, st, touch=False)
        render(root, st)
    register_project(root)
    print(data_dir(root) / "dashboard.html")


def build_parser():
    p = argparse.ArgumentParser(prog="progress.py", description=__doc__.splitlines()[0])
    p.add_argument("--project", help="project root (default: nearest dir with .claude/dashboard/)")
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("init")
    s.add_argument("--name")
    s.add_argument("--goal")
    s.add_argument("--tasks-from", help="existing backlog Markdown to display instead of owning tasks "
                                        "(e.g. notes/remaining.md)")
    s.add_argument("--decisions-from", help="notes dir whose 決めたこと tables are displayed as decisions")
    s.set_defaults(func=cmd_init)

    s = sub.add_parser("goal")
    s.add_argument("text")
    s.set_defaults(func=cmd_goal)

    s = sub.add_parser("task")
    ts = s.add_subparsers(dest="action", required=True)
    a = ts.add_parser("add")
    a.add_argument("title")
    a.add_argument("--status", choices=("todo", "doing", "unverified", "blocked"))
    a.add_argument("--note")
